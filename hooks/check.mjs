#!/usr/bin/env node
// Run My Agents: warn a Claude Code session before it edits a file
// that another session on this computer edited in the last few minutes.
//
//   session A edits api.ts ──► claims.json { "/repo/api.ts": { session: A, ... } }
//   session B edits api.ts ──► sees A's claim ──► edit stopped once, with a note
//   session B edits again  ──► allowed (a warning, not a lock)
//   session A edits again later ──► B is warned again before its next edit, naming A

import { execFileSync } from "node:child_process";
import { appendFileSync, mkdirSync, readFileSync, realpathSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { basename, dirname, isAbsolute, join, resolve } from "node:path";

const DIR = process.env.RUN_MY_AGENTS_DIR || join(homedir(), ".run-my-agents");
const FILE = join(DIR, "claims.json");

/** Positive finite minutes, else the documented default of 10 (#3). */
function ttlMsFromEnv(raw = process.env.RUN_MY_AGENTS_TTL_MINUTES) {
  const minutes = raw === undefined || raw === "" ? 10 : Number(raw);
  if (!Number.isFinite(minutes) || minutes <= 0) return 10 * 60_000;
  return minutes * 60_000;
}

const TTL_MS = ttlMsFromEnv();
/** warn (default) or off (#8). */
const MODE = process.env.RUN_MY_AGENTS_MODE === "off" ? "off" : "warn";
const DEBUG = process.env.RUN_MY_AGENTS_DEBUG === "1";

/** With RUN_MY_AGENTS_DEBUG=1, every decision and error goes to DIR/debug.log, since the hook never prints errors (#8). */
function debug(...parts) {
  if (!DEBUG) return;
  try {
    mkdirSync(DIR, { recursive: true });
    appendFileSync(join(DIR, "debug.log"), `${new Date().toISOString()} ${parts.map((x) => (x instanceof Error ? x.stack || x.message : typeof x === "string" ? x : JSON.stringify(x))).join(" ")}\n`);
  } catch {}
}

/**
 * Files that never get a claim or a warning (#7): lockfiles and generated output, which every session rewrites,
 * plus RUN_MY_AGENTS_IGNORE (comma-separated globs). A glob without a slash matches the file name anywhere; one with
 * a slash matches the end of the path. * stays inside one folder, ** crosses folders.
 */
const DEFAULT_IGNORE = ["package-lock.json", "bun.lock", "bun.lockb", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock", "poetry.lock", "uv.lock", "Gemfile.lock", "composer.lock", "go.sum", "*.autogenerated.*", "*.generated.*", "node_modules/**", "dist/**", ".flisk/**"];
function globRe(glob) {
  const body = glob
    .replace(/[.+^${}()|[\]\\]/g, "\\$&")
    .replace(/\*\*\/?/g, "\u0000")
    .replace(/\*/g, "[^/]*")
    .replace(/\?/g, "[^/]")
    .replace(/\u0000/g, ".*");
  return new RegExp(`(^|/)${body}$`);
}
export function ignored(file, extra = process.env.RUN_MY_AGENTS_IGNORE || "") {
  const globs = [...DEFAULT_IGNORE, ...extra.split(",").map((g) => g.trim()).filter(Boolean)];
  return globs.some((g) => (g.includes("/") ? globRe(g).test(file) : globRe(g).test(basename(file))));
}
const LOCK = join(DIR, "claims.lock");

/**
 * Two hooks that read claims.json at the same moment would each write back a copy without the other's claim.
 * A lock directory (mkdir is atomic) makes the read, change and rename one step. A lock older than 5 seconds is a
 * crashed hook's and is taken over. After about 2 seconds without the lock we go on without it: this hook never
 * stops an edit because of its own bookkeeping.
 */
function lock() {
  const pause = new Int32Array(new SharedArrayBuffer(4));
  const until = Date.now() + 2000;
  for (;;) {
    try {
      mkdirSync(LOCK);
      let held = true;
      return () => {
        if (held) rmSync(LOCK, { recursive: true, force: true });
        held = false;
      };
    } catch {
      try {
        if (Date.now() - statSync(LOCK).mtimeMs > 5000) rmSync(LOCK, { recursive: true, force: true });
      } catch {}
      if (Date.now() > until) return () => {};
      Atomics.wait(pause, 0, 0, 10 + Math.floor(Math.random() * 20));
    }
  }
}

/**
 * The key a claim is stored under. Two sessions can reach one file through a symlinked folder, or with a different
 * letter case on a case-insensitive disk (macOS), and must get the same key. The file may not exist yet (a Write
 * that creates it), so fall back to the real path of its folder.
 */
function keyOf(file) {
  try {
    return realpathSync.native(file);
  } catch {
    try {
      return join(realpathSync.native(dirname(file)), basename(file));
    } catch {
      return file;
    }
  }
}

function readJson(path, fallback) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return fallback;
  }
}

function branchOf(dir) {
  try {
    return execFileSync("git", ["-C", dir, "branch", "--show-current"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "";
  }
}

function ago(ms) {
  const min = Math.round(ms / 60_000);
  return min < 1 ? "just now" : `${min} min ago`;
}

/** SessionEnd: drop the ended session's claims, so a finished session never warns anyone (#6). */
function release(session) {
  mkdirSync(DIR, { recursive: true });
  const unlock = lock();
  process.on("exit", unlock);
  const state = readJson(FILE, { claims: {}, warned: {} });
  const claims = Object.fromEntries(Object.entries(state.claims || {}).filter(([, c]) => c.session !== session));
  const warned = Object.fromEntries(Object.entries(state.warned || {}).filter(([k]) => !k.startsWith(`${session}|`) && !k.endsWith(`|${session}`)));
  const tmp = `${FILE}.${process.pid}.tmp`;
  writeFileSync(tmp, JSON.stringify({ claims, warned }, null, 2));
  renameSync(tmp, FILE);
  unlock();
  debug("released", session, Object.keys(state.claims || {}).length - Object.keys(claims).length, "claims");
}

function main() {
  const input = readJson(0, {});
  const session = input.session_id;
  if (session && input.hook_event_name === "SessionEnd") return release(session);
  if (MODE === "off") return debug("off", session);
  const tool = input.tool_input || {};
  const raw = tool.file_path || tool.notebook_path;
  if (!session || !raw) return;
  if (ignored(isAbsolute(raw) ? raw : resolve(input.cwd || process.cwd(), raw))) return debug("ignored", raw);

  const cwd = input.cwd || process.cwd();
  const file = keyOf(isAbsolute(raw) ? raw : resolve(cwd, raw));
  const now = Date.now();

  mkdirSync(DIR, { recursive: true });
  const unlock = lock();
  process.on("exit", unlock);
  const state = readJson(FILE, { claims: {}, warned: {} });
  const claims = {};
  for (const [path, claim] of Object.entries(state.claims || {})) {
    if (now - claim.at < TTL_MS) claims[path] = claim;
  }
  const warned = {};
  for (const [key, at] of Object.entries(state.warned || {})) {
    if (now - at < TTL_MS) warned[key] = at;
  }

  const other = claims[file];
  const warnKey = other ? `${session}|${file}|${other.session}` : "";
  // A warning covers the other session's edits up to the moment it was given. If that session edits the file again
  // afterwards, this session is warned again (naming it), so it never overwrites newer work without being told.
  // A retry right after a warning still goes through: the other session has not edited since.
  let block = false;
  let again = false;
  if (other && other.session !== session && !(warned[warnKey] >= other.at)) {
    again = Boolean(warned[warnKey]);
    warned[warnKey] = now;
    block = true;
  }
  if (!block) claims[file] = { session, at: now, cwd, branch: branchOf(cwd) };

  const tmp = `${FILE}.${process.pid}.tmp`;
  writeFileSync(tmp, JSON.stringify({ claims, warned }, null, 2));
  renameSync(tmp, FILE);
  unlock();

  debug(block ? "warned" : "claimed", session, file, block ? `held by ${other.session}` : "");
  if (!block) return;
  const where = other.branch ? ` on branch ${other.branch}` : "";
  const drops = Math.max(1, Math.ceil((other.at + TTL_MS - now) / 60_000));
  const reason =
    `Run My Agents: another Claude session (${other.session.slice(0, 8)}${where}, in ${other.cwd}) ` +
    `edited ${basename(file)} ${again ? "again since you were warned, " : ""}${ago(now - other.at)}. ` +
    `Its claim drops in ${drops} min, or when that session ends. ` +
    "Your edit could overwrite its work. Read the file again first, or work on a different file. " +
    "If you are sure, make the edit again and it will go through.";
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason: reason,
      },
    }),
  );
}

// Run only as a hook, not when a test imports ignored().
const runAsHook = (() => {
  try {
    return realpathSync.native(process.argv[1]) === realpathSync.native(new URL(import.meta.url).pathname);
  } catch {
    return false;
  }
})();
if (runAsHook) {
  try {
    main();
  } catch (e) {
    // Never stop an edit because this hook broke.
    debug("error", e);
  }
}
